#!/bin/bash
# Install rules/global-rules.md and rules/user-bootstrap.md into every
# Hearth-supported client that has a file-based rules path.
#
#   scripts/install-global-rules.sh          # install / update
#   scripts/install-global-rules.sh --show   # print sources, change nothing
#   scripts/install-global-rules.sh --check  # report destinations, change nothing
#
# Marker files (Claude, ~/.agents, OpenCode, Zed): each pack sits between
# <!-- BEGIN hearth … --> / <!-- END hearth … -->. Re-runs replace the block
# only. Text outside the markers is left alone.
#
# Legacy: <!-- BEGIN ai-stack global rules --> is treated as the global-rules
# slot and rewritten to hearth markers (no duplicate).
#
# Dedicated files (Cursor ~/.cursor/rules/hearth-*.mdc, Cline
# ~/Documents/Cline/Rules/hearth-*.md): overwrite only those filenames.
# Never touch Cursor Settings → User Rules or state.vscdb.
#
# VS Code Chat, JetBrains AI Assistant, aider and Xcode use the project
# AGENTS.md / CLAUDE.md when in a repo; this script does not write for them.

set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC_GLOBAL="${ROOT}/rules/global-rules.md"
SRC_BOOT="${ROOT}/rules/user-bootstrap.md"

BEGIN_GLOBAL="<!-- BEGIN hearth global rules -->"
END_GLOBAL="<!-- END hearth global rules -->"
BEGIN_BOOT="<!-- BEGIN hearth user bootstrap -->"
END_BOOT="<!-- END hearth user bootstrap -->"
LEGACY_BEGIN="<!-- BEGIN ai-stack global rules -->"
LEGACY_END="<!-- END ai-stack global rules -->"

[ -f "$SRC_GLOBAL" ] || { echo "missing ${SRC_GLOBAL}" >&2; exit 1; }
[ -f "$SRC_BOOT" ] || { echo "missing ${SRC_BOOT}" >&2; exit 1; }

# Body: drop the H1, keep from the first ## onward (skip install preamble).
src_body() {
  awk 'NR>1' "$1" | awk '/^## /{p=1} p'
}

# Strip one marker pair from stdin. Optional second pair (legacy).
strip_markers() {
  awk -v b1="$1" -v e1="$2" -v b2="${3:-}" -v e2="${4:-}" '
    BEGIN { skip=0 }
    b1 != "" && index($0,b1) { skip=1; next }
    e1 != "" && index($0,e1) { skip=0; next }
    b2 != "" && index($0,b2) { skip=1; next }
    e2 != "" && index($0,e2) { skip=0; next }
    !skip { print }
  '
}

# Collapse trailing blank lines on stdin.
trim_trailing_blanks() {
  awk 'BEGIN{n=0} {lines[NR]=$0} END{
    last=NR
    while (last>0 && lines[last] ~ /^[[:space:]]*$/) last--
    for (i=1; i<=last; i++) print lines[i]
  }'
}

# Upsert one marked pack into DEST. Args: dest begin end title source_rel body
# For global, also strips legacy ai-stack markers.
upsert_marked() {
  _dest="$1"
  _begin="$2"
  _end="$3"
  _title="$4"
  _src_rel="$5"
  _body="$6"
  _is_global="${7:-0}"

  mkdir -p "$(dirname "$_dest")"
  [ -f "$_dest" ] || : > "$_dest"

  _tmp="$(mktemp)"
  if [ "$_is_global" = "1" ]; then
    strip_markers "$_begin" "$_end" "$LEGACY_BEGIN" "$LEGACY_END" < "$_dest" > "$_tmp"
  else
    strip_markers "$_begin" "$_end" < "$_dest" > "$_tmp"
  fi

  if grep -qF "$_begin" "$_dest" 2>/dev/null \
     || { [ "$_is_global" = "1" ] && grep -qF "$LEGACY_BEGIN" "$_dest" 2>/dev/null; }; then
    _action="updated"
  else
    _action="added to"
  fi

  {
    trim_trailing_blanks < "$_tmp"
    [ -s "$_tmp" ] && echo
    echo "$_begin"
    echo "$_title"
    echo
    echo "Source: ${_src_rel} — edit there, then re-run"
    echo "scripts/install-global-rules.sh. Do not edit between these markers."
    echo
    printf '%s\n' "$_body"
    echo "$_end"
  } > "${_tmp}.new"

  mv "${_tmp}.new" "$_dest"
  rm -f "$_tmp"
  echo "${_action} ${_dest} (${_title})"
}

write_dedicated() {
  _dest="$1"
  _kind="$2"   # mdc | md
  _desc="$3"
  _title="$4"
  _src_rel="$5"
  _body="$6"

  mkdir -p "$(dirname "$_dest")"
  if [ -f "$_dest" ]; then
    _action="updated"
  else
    _action="wrote"
  fi

  {
    if [ "$_kind" = "mdc" ]; then
      echo "---"
      echo "description: ${_desc}"
      echo "alwaysApply: true"
      echo "---"
      echo
    fi
    echo "$_title"
    echo
    echo "Source: ${_src_rel} — edit there, then re-run"
    echo "scripts/install-global-rules.sh. Do not edit this file by hand."
    echo
    printf '%s\n' "$_body"
  } > "$_dest"

  echo "${_action} ${_dest}"
}

check_marked() {
  _label="$1"
  _dest="$2"
  if [ ! -f "$_dest" ]; then
    echo "  ${_label}: missing ${_dest}"
    return
  fi
  _g="no"; _b="no"; _leg="no"
  grep -qF "$BEGIN_GLOBAL" "$_dest" 2>/dev/null && _g="yes"
  grep -qF "$BEGIN_BOOT" "$_dest" 2>/dev/null && _b="yes"
  grep -qF "$LEGACY_BEGIN" "$_dest" 2>/dev/null && _leg="yes"
  echo "  ${_label}: ${_dest}"
  echo "    hearth global=${_g}  hearth bootstrap=${_b}  legacy ai-stack=${_leg}"
  if [ "$_leg" = "yes" ]; then
    echo "    would migrate ai-stack → hearth global on install"
  fi
}

check_dedicated() {
  _label="$1"
  _dest="$2"
  if [ -f "$_dest" ]; then
    echo "  ${_label}: present ${_dest}"
  else
    echo "  ${_label}: missing ${_dest} (would write)"
  fi
}

BODY_GLOBAL="$(src_body "$SRC_GLOBAL")"
BODY_BOOT="$(src_body "$SRC_BOOT")"

CLAUDE_DEST="${CLAUDE_GLOBAL:-$HOME/.claude/CLAUDE.md}"
AGENTS_DEST="${HEARTH_AGENTS_GLOBAL:-$HOME/.agents/AGENTS.md}"
OPENCODE_DEST="${HEARTH_OPENCODE_AGENTS:-$HOME/.config/opencode/AGENTS.md}"
ZED_DEST="${HEARTH_ZED_AGENTS:-$HOME/.config/zed/AGENTS.md}"
CURSOR_RULES="${HEARTH_CURSOR_RULES:-$HOME/.cursor/rules}"
CLINE_RULES="${HEARTH_CLINE_RULES:-$HOME/Documents/Cline/Rules}"

if [ "${1:-}" = "--show" ]; then
  echo "===== ${SRC_GLOBAL} ====="
  cat "$SRC_GLOBAL"
  echo
  echo "===== ${SRC_BOOT} ====="
  cat "$SRC_BOOT"
  exit 0
fi

if [ "${1:-}" = "--check" ]; then
  echo "Hearth portable rules — check (no writes)"
  echo
  echo "Sources:"
  echo "  ${SRC_GLOBAL}"
  echo "  ${SRC_BOOT}"
  echo
  echo "Marker destinations:"
  check_marked "Claude Code" "$CLAUDE_DEST"
  check_marked "~/.agents (Cline cross-tool)" "$AGENTS_DEST"
  check_marked "OpenCode" "$OPENCODE_DEST"
  check_marked "Zed" "$ZED_DEST"
  echo
  echo "Dedicated destinations:"
  check_dedicated "Cursor global" "${CURSOR_RULES}/hearth-global-rules.mdc"
  check_dedicated "Cursor bootstrap" "${CURSOR_RULES}/hearth-user-bootstrap.mdc"
  check_dedicated "Cline Desktop global" "${CLINE_RULES}/hearth-global-rules.md"
  check_dedicated "Cline Desktop bootstrap" "${CLINE_RULES}/hearth-user-bootstrap.md"
  echo
  echo "No global file install (project AGENTS.md / CLAUDE.md): VS Code Chat,"
  echo "JetBrains AI Assistant, aider, Xcode."
  echo "Cursor Settings → User Rules and state.vscdb are never touched."
  exit 0
fi

if [ -n "${1:-}" ]; then
  echo "usage: $0 [--show|--check]" >&2
  exit 2
fi

# --- Marker installs ---
upsert_marked "$CLAUDE_DEST" "$BEGIN_GLOBAL" "$END_GLOBAL" \
  "# Global engineering rules" "rules/global-rules.md" "$BODY_GLOBAL" 1
upsert_marked "$CLAUDE_DEST" "$BEGIN_BOOT" "$END_BOOT" \
  "# User agent bootstrap" "rules/user-bootstrap.md" "$BODY_BOOT" 0

upsert_marked "$AGENTS_DEST" "$BEGIN_GLOBAL" "$END_GLOBAL" \
  "# Global engineering rules" "rules/global-rules.md" "$BODY_GLOBAL" 1
upsert_marked "$AGENTS_DEST" "$BEGIN_BOOT" "$END_BOOT" \
  "# User agent bootstrap" "rules/user-bootstrap.md" "$BODY_BOOT" 0

upsert_marked "$OPENCODE_DEST" "$BEGIN_GLOBAL" "$END_GLOBAL" \
  "# Global engineering rules" "rules/global-rules.md" "$BODY_GLOBAL" 1
upsert_marked "$OPENCODE_DEST" "$BEGIN_BOOT" "$END_BOOT" \
  "# User agent bootstrap" "rules/user-bootstrap.md" "$BODY_BOOT" 0

upsert_marked "$ZED_DEST" "$BEGIN_GLOBAL" "$END_GLOBAL" \
  "# Global engineering rules" "rules/global-rules.md" "$BODY_GLOBAL" 1
upsert_marked "$ZED_DEST" "$BEGIN_BOOT" "$END_BOOT" \
  "# User agent bootstrap" "rules/user-bootstrap.md" "$BODY_BOOT" 0

# --- Dedicated Cursor (user-level rules dir; not Settings User Rules) ---
write_dedicated "${CURSOR_RULES}/hearth-global-rules.mdc" mdc \
  "Hearth portable engineering rules (bash 3.2, Mermaid, checks)" \
  "# Global engineering rules" "rules/global-rules.md" "$BODY_GLOBAL"
write_dedicated "${CURSOR_RULES}/hearth-user-bootstrap.mdc" mdc \
  "Hearth user agent bootstrap (plan, minimum code, verify)" \
  "# User agent bootstrap" "rules/user-bootstrap.md" "$BODY_BOOT"

# --- Dedicated Cline Desktop ---
write_dedicated "${CLINE_RULES}/hearth-global-rules.md" md \
  "" "# Global engineering rules" "rules/global-rules.md" "$BODY_GLOBAL"
write_dedicated "${CLINE_RULES}/hearth-user-bootstrap.md" md \
  "" "# User agent bootstrap" "rules/user-bootstrap.md" "$BODY_BOOT"

cat <<EOF

Done. Re-run anytime; marker blocks and hearth-* files update in place.

Cursor: ~/.cursor/rules/hearth-*.mdc (alwaysApply). Settings → User Rules
are not modified — remove a hand-pasted duplicate there if you still have one.

No global install for: VS Code Chat, JetBrains AI Assistant, aider, Xcode
(they use the repo AGENTS.md / CLAUDE.md inside a Hearth checkout).

Check without writing:  scripts/install-global-rules.sh --check
Print sources:          scripts/install-global-rules.sh --show
EOF
